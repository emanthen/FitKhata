import axios from "axios";

import { httpClient } from "./http-client";

/** Separate from the JWT-based `httpClient` instance in http-client.ts on
 * purpose: a paired gate kiosk authenticates with `Authorization: Device
 * <token>`, not a Bearer JWT — it has no refresh token to retry with, and a
 * 403 here is a validation decision the gate UI handles itself, not a
 * reason to redirect to the staff /403 page. So this gets its own bare
 * axios instance with none of httpClient's interceptors.
 */
const deviceAxios = axios.create({
  baseURL: process.env.NEXT_PUBLIC_API_URL ?? "http://localhost:8000",
});

function deviceHeaders(token: string) {
  return { Authorization: `Device ${token}` };
}

// --- device-token endpoints (gate kiosk) ------------------------------

export interface PairDeviceResult {
  device_id: number;
  gym_id: string;
  token: string;
}

/** No auth — the pairing code itself (generated by a manager, see
 * createPairingCode below) is the proof of authorization.
 */
export const pairDevice = (code: string, deviceName: string): Promise<PairDeviceResult> =>
  deviceAxios
    .post("/api/v1/gate/pair", { code, device_name: deviceName })
    .then((r) => r.data);

export interface GateSnapshotMember {
  member_code: string;
  member_id: number;
  qr_secret: { nonce: string; ciphertext: string };
  status: string;
  expiry_date: string | null;
  access_hours: Record<string, unknown>;
  dues_npr: string;
  photo_url: string | null;
  card_uid: string;
  updated_at: string;
}

export interface GateSnapshotResponse {
  members: GateSnapshotMember[];
  server_time: string;
}

export const fetchGateSnapshot = (
  token: string,
  since?: string
): Promise<GateSnapshotResponse> =>
  deviceAxios
    .get("/api/v1/gate/snapshot", {
      headers: deviceHeaders(token),
      params: since ? { since } : undefined,
    })
    .then((r) => r.data);

export type CheckinSource = "qr_gate" | "front_desk_manual" | "biometric" | "rfid";

export interface CheckinRow {
  client_uuid: string;
  member_code: string;
  check_in_at: string;
  source: CheckinSource;
}

export interface CheckinsBatchResult {
  accepted: string[];
  duplicates: string[];
  rejected: { client_uuid: string; reason: string }[];
}

export const postCheckinsBatch = (
  token: string,
  checkins: CheckinRow[]
): Promise<CheckinsBatchResult> =>
  deviceAxios
    .post("/api/v1/gate/checkins:batch", { checkins }, { headers: deviceHeaders(token) })
    .then((r) => r.data);

// --- unauthenticated endpoint (member pass link redemption) -----------

export interface MemberPassRedemption {
  member_id: number;
  member_code: string;
  full_name: string;
  gym_code: string;
  qr_secret_hex: string;
}

export const redeemMemberPass = (token: string): Promise<MemberPassRedemption> =>
  deviceAxios.get(`/api/v1/m/pass/${token}`).then((r) => r.data);

// --- JWT-authenticated endpoints (staff, via the normal httpClient) ---

export const createPairingCode = (
  deviceName: string
): Promise<{ code: string; expires_in: number }> =>
  httpClient({
    method: "POST",
    url: "/api/v1/gate/pairing-codes",
    data: { device_name: deviceName },
  });

export const manualCheckin = (
  memberId: number,
  reason = ""
): Promise<{ id: number; check_in_at: string }> =>
  httpClient({
    method: "POST",
    url: "/api/v1/attendance/manual",
    data: { member_id: memberId, reason },
  });

export const createMemberPassLink = (memberId: number): Promise<{ token: string }> =>
  httpClient({
    method: "POST",
    url: "/api/v1/attendance/member-pass-links",
    data: { member_id: memberId },
  });

// --- Member self-login by phone OTP (FR-8.2) ---------------------------

export const sendMemberLoginOtp = (phone: string): Promise<void> =>
  deviceAxios.post("/api/v1/m/login/otp/send", { phone }).then(() => undefined);

export interface MemberLoginResult extends MemberPassRedemption {
  token: string;
}

export const verifyMemberLoginOtp = (
  phone: string,
  code: string,
  gymCode: string
): Promise<MemberLoginResult> =>
  deviceAxios
    .post("/api/v1/m/login/otp/verify", { phone, code, gym_code: gymCode })
    .then((r) => r.data);

// --- Member attendance calendar + streak (FR-8.3/8.4) -------------------

export interface MemberAttendanceCalendar {
  visit_dates: string[];
  current_streak: number;
  longest_streak: number;
}

export const getMemberAttendanceCalendar = (
  passToken: string
): Promise<MemberAttendanceCalendar> =>
  httpClient({ method: "GET", url: `/api/v1/m/pass/${passToken}/attendance` });
